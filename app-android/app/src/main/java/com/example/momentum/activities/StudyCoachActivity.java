
package com.example.momentum.activities;

import android.os.Bundle;
import android.view.Gravity;
import android.view.View;
import android.widget.Button;
import android.widget.EditText;
import android.widget.LinearLayout;
import android.widget.ScrollView;
import android.widget.TextView;
import android.widget.Toast;

import androidx.appcompat.app.AppCompatActivity;

import com.example.momentum.R;
import com.example.momentum.data.EasterEggs;

import java.util.Locale;

public class StudyCoachActivity extends BaseActivity {

    private LinearLayout chatMessages;
    private EditText editMessage;
    private ScrollView chatScroll;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        setContentView(R.layout.activity_study_coach);

        chatMessages = findViewById(R.id.chatMessages);
        editMessage = findViewById(R.id.editMessage);
        chatScroll = findViewById(R.id.chatScroll);

        Button btnSend = findViewById(R.id.btnSend);
        Button btnBack = findViewById(R.id.btnBack);
        Button btnStudyPlan = findViewById(R.id.btnStudyPlan);
        Button btnExplain = findViewById(R.id.btnExplain);
        Button btnQuiz = findViewById(R.id.btnQuiz);

        btnBack.setOnClickListener(v -> finish());

        btnSend.setOnClickListener(v -> sendMessage());

        btnStudyPlan.setOnClickListener(v ->
                sendSuggestedMessage("Make me a study plan"));

        btnExplain.setOnClickListener(v ->
                sendSuggestedMessage("Explain a difficult topic"));

        btnQuiz.setOnClickListener(v ->
                sendSuggestedMessage("Quiz me"));

        addMessage("Hello! I'm your Study Coach. "
                        + "I can help you plan your studies, understand topics, "
                        + "and practise for tests. What would you like help with?",
                false);
    }

    private void sendMessage() {
        String message = editMessage.getText().toString().trim();

        if (message.isEmpty()) {
            Toast.makeText(this, "Please type a message first.",
                    Toast.LENGTH_SHORT).show();
            return;
        }

        editMessage.setText("");
        sendSuggestedMessage(message);
    }

    private void sendSuggestedMessage(String message) {
        addMessage(message, true);


        // Easter egg: asking about Bartholomew unlocks a secret badge
        if (message.toLowerCase(Locale.ROOT).contains("bartholomew")) {
            EasterEggs.report(this, EasterEggs.ASKED_BARTHOLOMEW);
        }

        // Demo assistant: answers are predefined, not generated by AI.
        String response = getCoachResponse(message);

        chatMessages.postDelayed(() -> {
            addMessage(response, false);
        }, 350);
    }

    private String getCoachResponse(String message) {
        String text = message.toLowerCase(Locale.ROOT);


        // The legend himself
        if (text.contains("bartholomew")) {
            return "Ah, Bartholomew Crownelius the Third! The legendary learner who earned 333 points "
                    + "back in October 1066, and still sits on the all-time leaderboard. "
                    + "Nobody knows how he did it, but they say he never once skipped a check-in.";
        }

        if (text.contains("hello") || text.contains("hi ")
                || text.equals("hi") || text.contains("hey")) {
            return "Hello! I'm here to help you learn. "
                    + "Would you like a study plan, an explanation, or a quiz?";
        }

        if (text.contains("plan") || text.contains("timetable")
                || text.contains("schedule")) {
            return "Here is a simple study plan:\n\n"
                    + "1. Spend 10 minutes reviewing your notes.\n"
                    + "2. Study one topic for 25 minutes.\n"
                    + "3. Take a 5-minute break.\n"
                    + "4. Practise questions for 15 minutes.\n"
                    + "5. Spend 5 minutes summarising what you learned.\n\n"
                    + "Choose a time that fits your daily schedule, and save it "
                    + "in the Study Timetable on the Goals tab.";
        }

        if (text.contains("quiz") || text.contains("test")
                || text.contains("question")) {
            return "Let's practise! Answer this question:\n\n"
                    + "Which method is best for remembering what you study?\n\n"
                    + "A. Reading without a break\n"
                    + "B. Testing yourself on what you learned\n"
                    + "C. Leaving all revision until the last day\n\n"
                    + "Type A, B, or C to check your answer.";
        }

        if (text.trim().equals("b")) {
            return "Correct! B is the best answer. Testing yourself "
                    + "helps you retrieve information from memory. "
                    + "Try explaining the answer in your own words too.";
        }

        if (text.trim().equals("a") || text.trim().equals("c")) {
            return "Not quite! The best answer is B: testing yourself "
                    + "on what you learned. This is called active recall. "
                    + "Try another question when you're ready.";
        }

        if (text.contains("explain") || text.contains("understand")
                || text.contains("difficult") || text.contains("meaning")) {
            return "Let's make it easier to understand!\n\n"
                    + "1. Identify the main idea.\n"
                    + "2. Break it into smaller parts.\n"
                    + "3. Find a simple real-life example.\n"
                    + "4. Explain it in your own words.\n"
                    + "5. Practise with a question.\n\n"
                    + "If you can explain it to a friend in a few sentences, "
                    + "you understand it.";
        }

        if (text.contains("motivat") || text.contains("tired")
                || text.contains("give up") || text.contains("stress")) {
            return "You can make progress one small step at a time. "
                    + "Choose one task, study for 15 minutes, and take "
                    + "a short break. You do not need to learn everything "
                    + "at once. Consistency matters more than perfection!";
        }

        if (text.contains("java") || text.contains("programming")
                || text.contains("coding")) {
            return "Programming tip: practise by writing small programs.\n\n"
                    + "Start with variables, data types, if statements, "
                    + "loops, and methods. Run your code, read any errors, "
                    + "and fix one problem at a time.";
        }

        if (text.contains("thank")) {
            return "You're welcome! Keep learning and keep building "
                    + "your momentum. What would you like to study next?";
        }

        return "Thanks for your question!\n\n"
                + "I'm currently a demo Study Coach, so I use predefined "
                + "responses rather than understanding every question.\n\n"
                + "Try asking me to:\n"
                + "• Make a study plan\n"
                + "• Explain a difficult topic\n"
                + "• Quiz me\n"
                + "• Give me motivation\n\n"
                + "You can also tell me your subject for general study tips.";
    }

    private void addMessage(String message, boolean isUser) {
        TextView bubble = new TextView(this);
        bubble.setText(message);
        bubble.setTextSize(15);
        bubble.setTextColor(0xFF29243A);
        bubble.setPadding(30, 22, 30, 22);
        bubble.setMaxWidth((int) (getResources()
                .getDisplayMetrics().widthPixels * 0.78f));

        android.graphics.drawable.GradientDrawable background =
                new android.graphics.drawable.GradientDrawable();

        background.setColor(isUser ? 0xFFE9E0FF : 0xFFFFFFFF);
        background.setCornerRadius(28);
        background.setStroke(1, 0xFFE1D9F3);
        bubble.setBackground(background);

        LinearLayout.LayoutParams params =
                new LinearLayout.LayoutParams(
                        LinearLayout.LayoutParams.WRAP_CONTENT,
                        LinearLayout.LayoutParams.WRAP_CONTENT);

        params.setMargins(12, 8, 12, 8);
        params.gravity = isUser ? Gravity.END : Gravity.START;

        bubble.setLayoutParams(params);
        chatMessages.addView(bubble);

        chatScroll.post(() -> chatScroll.fullScroll(View.FOCUS_DOWN));
    }
}
